import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

function normalizeCommit(raw) {
  if (!raw) return null;
  const value = String(raw).trim();
  if (!value || value === 'unknown') return null;
  return value.slice(0, 12);
}

function tryGitRevParse(cwd) {
  try {
    return execSync('git rev-parse --short HEAD', {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

function resolveCommitHash(cliArg) {
  const fromCli = normalizeCommit(cliArg);
  if (fromCli) return fromCli;

  const fromEnv = normalizeCommit(
    process.env.GIT_COMMIT ??
      process.env.SOURCE_COMMIT ??
      process.env.COOLIFY_SOURCE_COMMIT ??
      process.env.GITHUB_SHA,
  );
  if (fromEnv) return fromEnv;

  for (const cwd of [root, join(root, '..'), join(root, '../..')]) {
    const hash = tryGitRevParse(cwd);
    if (hash) return hash;
  }

  return 'unknown';
}

const appVersion = pkg.version;
const commitHash = resolveCommitHash(process.argv[2]);

const content = `// Generated by scripts/inject-build-info.mjs — do not edit manually.
window.TRCON_APP_VERSION = '${appVersion}';
window.TRCON_COMMIT_HASH = '${commitHash}';
`;

writeFileSync(join(root, 'assets/build-info.js'), content, 'utf8');
console.log(`Build info: v${appVersion} @ ${commitHash}`);
